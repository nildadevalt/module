local UIS = game:GetService("UserInputService")
local vim = game:GetService("VirtualInputManager")
local n = 0
local c = UIS.InputBegan:Connect(function(i) n = n + 1 end)
local function t(label, fn)
  local ok, err = pcall(fn)
  task.wait(0.12)
  print(string.format("[VB] %-26s ok=%s err=%s events=%d", label, tostring(ok), tostring(err), n))
end
t("SendMouseButtonEvent(6 args)", function() vim:SendMouseButtonEvent(400, 300, 1, true, game, 1) end)
t("SendMouseButtonEvent(5 args)", function() vim:SendMouseButtonEvent(400, 300, 1, true, game) end)
t("SendMouseButtonEvent(4 args)", function() vim:SendMouseButtonEvent(400, 300, 1, true) end)
t("SendMouseMoveEvent", function() vim:SendMouseMoveEvent(400, 300, game) end)
t("SendMouseButtonEvent down", function() vim:SendMouseButtonEvent(400, 300, 1, true, game, 1) end)
task.wait(0.1)
print("[VB] down=" .. tostring(UIS:IsMouseButtonPressed(Enum.UserInputType.MouseButton1)))
t("SendMouseButtonEvent up", function() vim:SendMouseButtonEvent(400, 300, 1, false, game, 1) end)
print("[VB] down=" .. tostring(UIS:IsMouseButtonPressed(Enum.UserInputType.MouseButton1)))
c:Disconnect()
print("SUNCIO-DONE")
