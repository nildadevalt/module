print("[S2] start")
task.spawn(function()
    local s = Signal.new()
    task.delay(0.3, function() print("[S2] firing"); s:Fire("hello") end)
    local t0 = os.clock()
    local v = s:Wait()
    print("[S2] Wait returned " .. tostring(v) .. " t=" .. string.format("%.2f", os.clock()-t0))
    print("SUNCIO-DONE")
end)
print("[S2] spawned")
