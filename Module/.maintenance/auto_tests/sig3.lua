print("[S3] start")
task.spawn(function()
    local s = Signal.new()
    task.delay(0.1, function() print("[S3] firing at " .. string.format("%.2f", os.clock()-T0)); s:Fire("v") end)
    task.wait(0.45)
    print("[S3] subscribing at " .. string.format("%.2f", os.clock()-T0))
    local ok, v = pcall(function() return s:Wait() end)
    print("[S3] Wait done ok=" .. tostring(ok) .. " v=" .. tostring(v))
    print("SUNCIO-DONE")
end)
T0 = os.clock()
print("[S3] spawned")
