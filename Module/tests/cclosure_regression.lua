--!strict

assert(game.PlaceId == 90441122676618, "Wrong test place")
local native = clonefunction(math.abs)
local nativeEnv = getfenv(native)
local nativeName = debug.info(native, "n")
local parent
local parentName
local wrapper = newcclosure(function(value)
    parent = debug.info(2, "f")
    parentName = debug.info(2, "n")
    return value + 10
end)
local original = hookfunction(native, wrapper)
assert(native(2) == 12, "C-to-NC hook returned the wrong value")
assert(parent == native, "C-to-NC hook added another C closure frame")
assert(getfenv(native) == nativeEnv, "Hooking changed the native closure environment")
assert(parentName == nativeName, "Hooking changed the native closure's frame name")
assert(original(-2) == 2, "The saved native body changed")
local snapshot = clonefunction(native)
assert(restorefunction(native), "C-to-NC restoration failed")
assert(native(-2) == 2 and snapshot(2) == 12, "Restoration changed the clone snapshot")
assert(not isnewcclosure(native), "Restoration retained temporary wrapper metadata")
assert(restorefunction(snapshot), "Snapshot restoration failed")
assert(snapshot(-3) == 3 and not isnewcclosure(snapshot), "Snapshot retained its installed wrapper")
print("CCLOSURE-REGRESSION direct body and clone snapshot passed")

local first = newcclosure(function(value) return value + 10 end)
local second = newcclosure(function(value) return value + 20 end)
hookfunction(native, first)
local previous = hookfunction(native, second)
assert(native(2) == 22 and previous(2) == 12, "Chained C hooks lost the previous body")
assert(restorefunction(native) and native(-4) == 4, "Chained hooks did not restore the native body")
assert(previous(2) == 12, "Restoration changed the returned previous body")
print("CCLOSURE-REGRESSION chaining passed")

hookfunction(native, tonumber)
assert(native("17") == 17, "Native C-to-C hook did not run")
assert(restorefunction(native) and native(-5) == 5, "Native C-to-C restoration failed")
print("CCLOSURE-REGRESSION native body passed")

hookfunction(native, newcclosure(function(value)
    coroutine.yield("ready")
    return original(value)
end))
local co = coroutine.create(function() return native(-8) end)
local ok, value = coroutine.resume(co)
assert(ok and value == "ready", "C-to-NC hook did not yield")
ok, value = coroutine.resume(co)
assert(ok and value == 8, "C-to-NC hook did not resume")
assert(restorefunction(native), "Yielding hook restoration failed")
print("CCLOSURE-REGRESSION yielding passed")
print("CCLOSURE-REGRESSION-DONE")
